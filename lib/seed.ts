function stats(id: number) {
  const list = resenas.filter((r) => r.productoId === id);
  if (!list.length) return { rating: 0, resenas: 0 };
  const rating = Math.round((list.reduce((sum, r) => sum + r.calificacion, 0) / list.length) * 10) / 10;
  return { rating, resenas: list.length };
}

export const productos: Producto[] = base.map((p) => ({ ...p, ...stats(p.id) }));

export function withStats(list: Producto[], reviews: Resena[]): Producto[] {
  return list.map((p) => {
    const own = reviews.filter((r) => r.productoId === p.id);
    if (!own.length) return { ...p, rating: 0, resenas: 0 };
    const rating = Math.round((own.reduce((sum, r) => sum + r.calificacion, 0) / own.length) * 10) / 10;
    return { ...p, rating, resenas: own.length };
  });
}
